#!/usr/bin/env node
// Writes local .env files for every app and service, and sets the per-service database passwords.
// Safe to run again: existing secrets are kept. Requires `supabase start` to be running.
//   pnpm env:setup
import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url));
const services = ['catalogue', 'profile', 'recommendation', 'engagement', 'content'];
const ports = { gateway: 4000, catalogue: 4101, profile: 4102, recommendation: 4103, engagement: 4104, content: 4200 };

const readEnv = (file) =>
  existsSync(file)
    ? Object.fromEntries(
        readFileSync(file, 'utf8')
          .split('\n')
          .filter((l) => l && !l.startsWith('#') && l.includes('='))
          .map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]),
      )
    : {};
const writeEnv = (file, values) => {
  const body = Object.entries(values).map(([k, v]) => `${k}=${v}`).join('\n');
  writeFileSync(file, `# Generated by tools/scripts/setup-env.mjs — local development only, never commit.\n${body}\n`, { mode: 0o600 });
  console.log(`  wrote ${file.replace(root, '')}`);
};
const secret = (existing) => existing && !existing.includes('CHANGE_ME') ? existing : randomBytes(24).toString('hex');

// 1. Local Supabase details
let status;
try {
  status = JSON.parse(execFileSync('supabase', ['status', '-o', 'json'], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }));
} catch {
  console.error('Supabase is not running. Start it first: pnpm db:start');
  process.exit(1);
}
const dbHost = new URL(status.DB_URL);

// 2. Shared secrets (reused if already generated)
const infraFile = join(root, 'infra/docker/.env');
const infra = readEnv(infraFile);
const gatewayOld = readEnv(join(root, 'apps/gateway/.env'));
const shared = {
  RABBITMQ_USER: infra.RABBITMQ_USER ?? 'edulaunch',
  RABBITMQ_PASSWORD: secret(infra.RABBITMQ_PASSWORD),
  REDIS_PASSWORD: secret(infra.REDIS_PASSWORD),
  INTERNAL_TOKEN: secret(gatewayOld.INTERNAL_TOKEN),
};
console.log('Writing environment files:');
writeEnv(infraFile, { RABBITMQ_USER: shared.RABBITMQ_USER, RABBITMQ_PASSWORD: shared.RABBITMQ_PASSWORD, REDIS_PASSWORD: shared.REDIS_PASSWORD });
const rabbitUrl = `amqp://${shared.RABBITMQ_USER}:${shared.RABBITMQ_PASSWORD}@127.0.0.1:5672`;

// 3. One database role per service
const dbContainer = `supabase_db_${readFileSync(join(root, 'supabase/config.toml'), 'utf8').match(/project_id = "(.+)"/)[1]}`;
for (const svc of services) {
  const file = join(root, `services/${svc}/.env`);
  const old = readEnv(file);
  const password = secret(old.DATABASE_URL ? new URL(old.DATABASE_URL).password : undefined);
  // Hex passwords need no quoting; psql runs inside the Supabase container, so no local client is needed.
  execFileSync('docker', ['exec', dbContainer, 'psql', '-U', 'postgres', '-q', '-c', `alter role ${svc}_svc password '${password}'`], { stdio: 'inherit' });
  const values = {
    PORT: String(ports[svc]),
    DATABASE_URL: `postgresql://${svc}_svc:${password}@${dbHost.hostname}:${dbHost.port}/postgres`,
    INTERNAL_TOKEN: shared.INTERNAL_TOKEN,
  };
  if (svc !== 'content') values.RABBITMQ_URL = rabbitUrl;
  if (svc === 'recommendation') Object.assign(values, { CATALOGUE_URL: `http://127.0.0.1:${ports.catalogue}`, PROFILE_URL: `http://127.0.0.1:${ports.profile}` });
  if (svc === 'engagement') values.PROFILE_URL = `http://127.0.0.1:${ports.profile}`;
  writeEnv(file, values);
}

// 4. Gateway and web
writeEnv(join(root, 'apps/gateway/.env'), {
  PORT: String(ports.gateway),
  INTERNAL_TOKEN: shared.INTERNAL_TOKEN,
  SUPABASE_URL: status.API_URL,
  SUPABASE_JWT_SECRET: status.JWT_SECRET,
  REDIS_URL: `redis://:${shared.REDIS_PASSWORD}@127.0.0.1:6379`,
  CORS_ORIGINS: 'http://localhost:3000,http://127.0.0.1:3000',
  ...Object.fromEntries(services.map((s) => [`${s.toUpperCase()}_URL`, `http://127.0.0.1:${ports[s]}`])),
});
writeEnv(join(root, 'apps/web/.env.local'), {
  NEXT_PUBLIC_SUPABASE_URL: status.API_URL,
  NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: status.PUBLISHABLE_KEY ?? status.ANON_KEY,
  GATEWAY_URL: `http://127.0.0.1:${ports.gateway}`,
});
console.log('\nDone. Next: pnpm infra:up && pnpm db:migrate && pnpm dev');
