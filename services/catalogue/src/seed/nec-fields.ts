/**
 * The broad EduLaunch field an NEC code suggests, by its leading digits (most specific prefix wins).
 * Generic programmes (00) suggest none. Admins can change the fields of each programme.
 */
const BROAD_FIELD_BY_PREFIX: Array<[prefix: string, fieldKey: string]> = [
  ['01', 'education'],
  ['021', 'design'],
  ['02', 'social'],
  ['03', 'social'],
  ['042', 'social'],
  ['04', 'business'],
  ['05', 'pure-science'],
  ['06', 'computing'],
  ['073', 'design'],
  ['07', 'engineering'],
  ['08', 'pure-science'],
  ['09', 'health'],
  ['10', 'technical'],
];

export function broadFieldKeyFor(necCode: string): string | null {
  const match = BROAD_FIELD_BY_PREFIX.filter(([prefix]) => necCode.startsWith(prefix)).sort((a, b) => b[0].length - a[0].length)[0];
  return match ? match[1] : null;
}

export const necFieldsSeed: SeedDataset['necFields'] = NEC_FIELDS.map(([code, name]) => ({ code, name, fieldKey: broadFieldKeyFor(code) }));
